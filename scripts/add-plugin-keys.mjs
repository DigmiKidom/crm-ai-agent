/** Deep merge that never overwrites a string that is already translated. */
function merge(target, additions) {
  for (const [key, value] of Object.entries(additions)) {
    if (value && typeof value === "object" && !Array.isArray(value)) {
      if (!target[key] || typeof target[key] !== "object") target[key] = {};
      merge(target[key], value);
    } else if (!(key in target)) {
      target[key] = value;
    }
  }
  return target;
}

for (const [locale, additions] of Object.entries(ADDITIONS)) {
  const path = new URL(`../lib/i18n/dictionaries/${locale}.json`, import.meta.url);
  const dict = JSON.parse(readFileSync(path, "utf8"));
  merge(dict, additions);
  writeFileSync(path, `${JSON.stringify(dict, null, 2)}\n`);
  console.log(`${locale}: merged`);
}
